"""JLPT GO 2.0 PostgreSQL model (Schema v0.2, first implementation).

Only canonical IDs identify content. Every versioned relationship includes release_id.
Published snapshots must be protected by a restricted DB role / guarded publish
workflow before public launch. Schema intentionally supports draft-only imports.
"""
from sqlalchemy import (
    MetaData, Table, Column, Text, Integer, SmallInteger, BigInteger, Boolean,
    DateTime, ForeignKey, ForeignKeyConstraint, PrimaryKeyConstraint,
    UniqueConstraint, CheckConstraint, Index, func,
)
from sqlalchemy.dialects.postgresql import UUID, JSONB

metadata = MetaData()
J = JSONB
U = UUID(as_uuid=True)
T = DateTime(timezone=True)

def tbl(name: str, *columns, **kwargs):
    return Table(name, metadata, *columns, **kwargs)

def pk(*fields):
    return PrimaryKeyConstraint(*fields)

def fk(fields, target, name):
    return ForeignKeyConstraint(fields, target, name=name)

def pos():
    return CheckConstraint("position > 0")

